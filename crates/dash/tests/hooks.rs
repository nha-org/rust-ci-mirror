/// A built dash, as Makefile rust/build leaves it in the main checkout's private/live/rust: it names its commit, which the hook
/// greps for, and says it ran
fn built_dash(sha: &str) -> String {
    format!("#!/bin/sh\n# built from {sha}\necho \"built $*\" >> \"$HOOK_LOG\"\n")
}
// cargo and rustc, each linked under its name: says it ran, then passes
const BUILD_TOOL: &str = "#!/bin/sh\necho \"${0##*/} $*\" >> \"$HOOK_LOG\"\n";

impl Scratch {
    /// private/live/rust's `dash` and `commit`, the commit one of this tree's whose id is the same each run of one fixture (fixed
    /// dates), so its stand-in is new only once the files the fixture copies change; `named` is what the binary names, `sha` what the file says.
    fn built(&self, message: &str, named: bool) -> String {
        let out = self
            .command("git")
            .envs([
                ("GIT_AUTHOR_NAME", "t"),
                ("GIT_AUTHOR_EMAIL", "t@t"),
                ("GIT_COMMITTER_NAME", "t"),
                ("GIT_COMMITTER_EMAIL", "t@t"),
                ("GIT_AUTHOR_DATE", "1700000000 +0000"),
                ("GIT_COMMITTER_DATE", "1700000000 +0000"),
            ])
            .args(["commit-tree", "--no-gpg-sign", "-m", message, "HEAD^{tree}"])
            .output()
            .expect("git commit-tree");
        assert!(
            out.status.success(),
            "{}",
            String::from_utf8_lossy(&out.stderr)
        );
        let sha = String::from_utf8_lossy(&out.stdout).trim().to_string();
        let live = self.dir.0.join("main/private/live/rust");
        std::fs::create_dir_all(&live).expect("mkdir");
        std::fs::write(live.join("commit"), format!("{sha}\n")).expect("commit");
        let binary = live.join("dash");
        let _ = std::fs::remove_file(&binary);
        let text = built_dash(if named { &sha } else { "an older commit" });
        std::os::unix::fs::symlink(dash_meter::stand_in(&text), &binary).expect("dash");
        let tools = self.dir.0.join("tools");
        std::fs::create_dir_all(&tools).expect("mkdir");
        for tool in ["cargo", "rustc"] {
            let _ = std::fs::remove_file(tools.join(tool));
            std::os::unix::fs::symlink(dash_meter::stand_in(BUILD_TOOL), tools.join(tool))
                .expect(tool);
        }
        sha
    }

    /// `program` as a session runs it: no DASH_HOOK_BIN, the stand-in cargo and rustc first on PATH, each tool's line in hook.log
    fn unbuilt(&self, program: &str) -> Command {
        let mut command = self.command(program);
        let path = format!(
            "{}:{}:{}",
            self.dir.0.join("tools").display(),
            self.dir.0.join("nopython").display(),
            std::env::var("PATH").unwrap_or_default()
        );
        command
            .env_remove("DASH_HOOK_BIN")
            .env("HOOK_LOG", self.dir.0.join("hook.log"))
            .env("PATH", path);
        command
    }

    /// `git <args>` through .githooks with no DASH_HOOK_BIN: what each tool said, the log emptied for the next case
    fn ran(&self, args: &[&str]) -> String {
        let out = self
            .unbuilt("git")
            .args([
                "-c",
                "user.name=t",
                "-c",
                "user.email=t@t",
                "-c",
                "core.hooksPath=.githooks",
            ])
            .args(args)
            .output()
            .expect("git");
        assert!(
            out.status.success(),
            "git {args:?}: {}",
            String::from_utf8_lossy(&out.stderr)
        );
        let log = self.dir.0.join("hook.log");
        let said = std::fs::read_to_string(&log).unwrap_or_default();
        let _ = std::fs::remove_file(&log);
        said
    }
}

