const LOCK: &str = "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"bar\"\nversion = \"0.1.0\"\n\n[[package]]\nname = \"dash\"\nversion = \"0.1.0\"\n\n[[package]]\nname = \"dash-gate\"\nversion = \"0.1.0\"\n\n[[package]]\nname = \"foo\"\nversion = \"0.1.0\"\n";

struct Scratch {
    dir: TestDir,
    /// The checkout commits run in: the main one, or a linked worktree as a task session's
    root: PathBuf,
}

impl Scratch {
    /// The fixture, committed with no hook; every later commit runs the real one.
    fn new(name: &str, top: &Path) -> Self {
        let dir = TestDir::new(&format!("hooks-{name}"));
        let root = dir.0.join("main");
        let s = Self { dir, root };
        for path in [".githooks/pre-commit", ".githooks/pre-push", "bin/bounded"] {
            let to = s.path(path);
            std::fs::create_dir_all(to.parent().expect("a folder")).expect("mkdir");
            std::fs::copy(top.join(path), &to).expect(path); // its mode too
        }
        s.write("forge.env", "DEFAULT_BRANCH=main\n");
        s.write("rust/scripts-held.txt", HELD);
        s.write("private/docs/rfc-rust-unified.html", ORDER);
        for py in ["python3", "python"] {
            let shim = s.dir.0.join("nopython").join(py);
            std::fs::create_dir_all(shim.parent().expect("a folder")).expect("mkdir");
            std::fs::write(&shim, NO_PYTHON).expect("shim");
            std::fs::set_permissions(&shim, std::os::unix::fs::PermissionsExt::from_mode(0o755))
                .expect("chmod");
        }
        s.write("private/docs/p.html", h("‹p›keep this passage‹/p›\n"));
        s.write("private/dashboard/bin/toolchain", TOOLCHAIN_STUB);
        s.chmod_x("private/dashboard/bin/toolchain");
        s.write("private/dashboard/bin/helper", "one\n");
        s.write("private/dashboard/priv/commands/helper", "one\n");
        s.write("private/dashboard/lib/a.ex", "one\ntwo\n");
        s.write("private/docs/notes.exs", "one\n");
        s.write("src/a.clj", "one\n");
        s.write("notes.txt", "one\n");
        s.write("sandbox/approval.md", "one\n");
        s.write(
            "Makefile",
            "sandbox/check:\n\t@test ! -e sandbox/fail || { echo 'approval-number: section 3 names no tap'; exit 1; }\n",
        );
        s.write(
            "rust/Cargo.toml",
            "[workspace]\nmembers = [\"gate\", \"dash\", \"foo\", \"bar\"]\nresolver = \"3\"\n",
        );
        s.write("rust/Cargo.lock", LOCK);
        for (krate, name, file, body) in [
            ("gate", "dash-gate", "src/lib.rs", GATE_STUB),
            ("dash", "dash", "src/main.rs", "fn main() {}\n"),
            ("foo", "foo", "src/lib.rs", FOO_STUB),
            ("bar", "bar", "src/lib.rs", BAR_STUB),
        ] {
            s.write(
                &format!("rust/{krate}/Cargo.toml"),
                &format!("[package]\nname = \"{name}\"\nversion = \"0.1.0\"\nedition = \"2024\"\n"),
            );
            s.write(&format!("rust/{krate}/{file}"), body);
        }
        s.write("rust/gate/notes.txt", "one\n");
        // the hooks tests' own file, which the pre-commit's hooks-tests step runs when it changes
        s.write("rust/dash/tests/hooks.rs", "");
        s.write(".gitignore", "target/\n");
        s.git(&["init", "-q", "-b", "main"]);
        s.git(&["add", "."]);
        s.fixture("fixture");
        s.git(&["update-ref", "refs/remotes/origin/main", "HEAD"]);
        s
    }

    /// Commits from here on run in a linked worktree, where git gives the hook GIT_DIR (a main checkout's hook gets none):
    /// the rust-gate refusal of every task's rust/ commit showed there alone.
    fn worktree(mut self) -> Self {
        self.git(&["worktree", "add", "-q", "-b", "task/x", "../task"]);
        self.root = self.dir.0.join("task");
        self
    }

    fn path(&self, rel: &str) -> PathBuf {
        self.root.join(rel)
    }

    fn write(&self, rel: &str, text: &str) {
        let file = self.path(rel);
        std::fs::create_dir_all(file.parent().expect("a folder")).expect("mkdir");
        std::fs::write(file, text).expect("write");
    }

    fn chmod_x(&self, rel: &str) {
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(self.path(rel), std::fs::Permissions::from_mode(0o755))
            .expect("chmod");
    }

    /// Git here alone: the hook a test runs under sets GIT_DIR and GIT_INDEX_FILE, which would aim every git below at the
    /// real repository, and his global config (signing, fsmonitor) stays out. The hooks run this build's dash.
    fn command(&self, program: &str) -> Command {
        let mut command = Command::new(program);
        for (key, _) in std::env::vars_os().filter(|(k, _)| {
            let k = k.to_string_lossy();
            k.starts_with("GIT_")
                || k.starts_with("NEXTEST")
                || k == "CI"
                || k.starts_with("CARGO_")
        }) {
            command.env_remove(key);
        }
        command
            .env("GIT_CONFIG_GLOBAL", "/dev/null")
            .env("GIT_CONFIG_NOSYSTEM", "1")
            .env("DASH_HOOK_BIN", env!("CARGO_BIN_EXE_dash"))
            .env("DASH_BIN", self.dir.0.join("app"))
            .env("PREPUSH_KEEP_CHECKOUTS", "")
            .env(
                "PATH",
                format!(
                    "{}:{}",
                    self.dir.0.join("nopython").display(),
                    std::env::var("PATH").unwrap_or_default()
                ),
            )
            // no dashboard: comments-anchored reads the scratch's private/live alone
            .env("DASHBOARD_URL", "http://127.0.0.1:9")
            // the stub workspace builds in the scratch, outside the checkout, never in a checkout's target (rust/CLAUDE.md
            // rule 2)
            .env("CARGO_TARGET_DIR", self.dir.0.join("target"))
            .current_dir(&self.root);
        command
    }

    fn git(&self, args: &[&str]) {
        let out = self
            .command("git")
            .args(["-c", "user.name=t", "-c", "user.email=t@t"])
            .args(args)
            .output()
            .expect("git");
        assert!(
            out.status.success(),
            "git {args:?}: {}",
            String::from_utf8_lossy(&out.stderr)
        );
    }

    /// A commit with no hook: the state a push then sends
    fn fixture(&self, message: &str) {
        self.git(&["-c", "core.hooksPath=/dev/null", "commit", "-qm", message]);
    }

    /// `git <args>` through .githooks: its exit and all the hook printed.
    fn hooked(&self, args: &[&str]) -> (bool, String) {
        let out = self
            .command("git")
            .args([
                "-c",
                "user.name=t",
                "-c",
                "user.email=t@t",
                "-c",
                "core.hooksPath=.githooks",
            ])
            .args(args)
            .output()
            .expect("git");
        let said = String::from_utf8_lossy(&out.stdout).to_string()
            + &String::from_utf8_lossy(&out.stderr);
        (out.status.success(), said)
    }

    fn commit(&self) -> (bool, String) {
        self.hooked(&["commit", "-qm", "case"])
    }

    fn stage(&self, rel: &str, text: &str) {
        self.write(rel, text);
        self.git(&["add", rel]);
    }

    fn passes(&self, case: &str) {
        let (ok, said) = self.commit();
        assert!(ok, "{case}: refused\n{said}");
    }

    /// Refused, and what it printed holds `reason`; the index is put back for the next case.
    fn refuses(&self, case: &str, reason: &str) {
        let (ok, said) = self.commit();
        assert!(!ok, "{case}: committed\n{said}");
        assert!(said.contains(reason), "{case}: no « {reason} » in\n{said}");
        self.git(&["reset", "-q", "--hard"]);
    }

    /// A bare origin the worktree pushes to; origin/main stays the fixture
    fn remote(&self) -> &Self {
        let bare = self.dir.0.join("origin.git");
        self.git(&["init", "-q", "--bare", &bare.to_string_lossy()]);
        self.git(&["remote", "add", "origin", &bare.to_string_lossy()]);
        self
    }

    fn push(&self, to: &str) -> (bool, String) {
        self.hooked(&["push", "-q", "origin", &format!("HEAD:{to}")])
    }
}

/// The six cases of elixir-shrinks, now no-elixir: grown, shrunk, a docs .exs changed and a new .exs are refused; a
/// deleted .ex and a Rust-only change pass.
