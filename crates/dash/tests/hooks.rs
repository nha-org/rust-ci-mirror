/// done-when 5: the pre-push runs nextest with CI=1 on each crate touched since the merge-base (foo, and dash-gate always),
/// never an untouched one (bar fails whenever it runs); a failing test of a touched crate refuses the push.
#[test]
fn hook_pre_push_runs_the_touched_crates_tests_with_ci_set() {
    let _budget = TestBudget::new();
    let Some(top) = monorepo() else { return };
    let s = Scratch::new("push-rust", &top).worktree();
    s.remote();
    s.stage("rust/foo/notes.txt", "touched\n");
    s.fixture("foo changes");
    let (ok, said) = s.push("refs/heads/task/x");
    assert!(ok, "foo's test with CI=1, bar never run:\n{said}");
    let log = std::fs::read_to_string(s.dir.0.join("main/.git/worktrees/task/prepush.log"))
        .expect("prepush.log");
    // the selection: foo touched since the merge-base, dash-gate always, bar never; nextest with CI=1, and foo's test
    // itself asserts CI is 1 (FOO_STUB)
    let run = log
        .lines()
        .find(|l| l.starts_with("pre-push: CI=1 cargo "))
        .unwrap_or_else(|| panic!("no CI=1 nextest line in\n{log}"));
    assert_eq!(
        run, "pre-push: CI=1 cargo nextest run --locked --retries 2 -p dash-gate -p foo",
        "nextest with CI=1 on the touched crate and dash-gate alone"
    );
    assert!(
        !log.contains("Found: bar ran") && !log.contains("Found: CI is not 1"),
        "{log}"
    );
    // A push that only merges main into the head origin holds runs no Rust test (main's 0b335572b, PR 1441): main's own
    // commit makes foo's test fail, and the push still goes.
    let main = s.dir.0.join("main");
    let main = main.to_string_lossy();
    std::fs::write(s.dir.0.join("main/rust/foo/fail"), "").expect("main's fail");
    s.git(&["-C", &main, "add", "rust/foo/fail"]);
    s.git(&[
        "-C",
        &main,
        "-c",
        "core.hooksPath=/dev/null",
        "commit",
        "-qm",
        "main moves",
    ]);
    s.git(&[
        "-C",
        &main,
        "update-ref",
        "refs/remotes/origin/main",
        "HEAD",
    ]);
    s.git(&[
        "-c",
        "core.hooksPath=/dev/null",
        "merge",
        "-q",
        "--no-edit",
        "main",
    ]);
    let (ok, said) = s.push("refs/heads/task/x");
    assert!(
        ok && said.contains("pre-push: only main merged into the pushed head"),
        "{said}"
    );
    s.stage("rust/foo/notes.txt", "touched again\n");
    s.fixture("foo's test fails");
    let (ok, said) = s.push("refs/heads/task/x");
    assert!(!ok && said.contains("Found: foo fails"), "{said}");
    assert!(
        said.contains("pre-push: the tests of the Rust crates this branch affects fail"),
        "{said}"
    );
}
