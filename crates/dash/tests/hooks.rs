/// Each step reads what is staged, never the working tree (done-when 4): a file staged then edited is judged as staged. A
/// bad file staged then deleted on disk is refused; a good state staged, then a bad file left on disk, unstaged, passes.
/// Both for a cargo step (rust-gate) and a file-reading check (offline-check).
#[test]
fn hook_steps_check_the_staged_content_never_the_working_tree() {
    let _budget = TestBudget::new();
    let Some(top) = monorepo() else { return };
    let s = Scratch::new("staged", &top).worktree();
    s.stage("rust/refuse", "one\n");
    std::fs::remove_file(s.path("rust/refuse")).expect("rm");
    let (ok, said) = s.commit();
    assert!(
        !ok && said.contains("pre-commit: dash-gate fails on this tree"),
        "rust/refuse staged, gone on disk:\n{said}"
    );
    s.git(&["reset", "-q", "--hard"]);
    s.stage("rust/gate/notes.txt", "two\n");
    s.write("rust/refuse", "on disk only\n");
    s.write("rust/gate/notes.txt", "edited after staging\n");
    s.passes("a good rust/ change staged, rust/refuse on disk");
    std::fs::remove_file(s.path("rust/refuse")).expect("rm");
    s.git(&["checkout", "-q", "--", "."]);
    let cdn = "private/docs/cdn.html";
    s.stage(cdn, h("‹script src=\"https://cdn.x/y.js\"›‹/script›\n"));
    s.write(cdn, h("‹p›fixed on disk, not staged‹/p›\n"));
    let (ok, said) = s.commit();
    assert!(
        !ok && said.contains("pre-commit: offline-check refused this commit"),
        "a CDN script staged, fixed on disk only:\n{said}"
    );
    // reset --hard takes the staged new page out of the work tree too
    s.git(&["reset", "-q", "--hard"]);
    s.stage("notes.txt", "two\n");
    s.write(cdn, h("‹script src=\"https://cdn.x/y.js\"›‹/script›\n"));
    s.passes("a clean change staged, a CDN script on disk only");
    // `git commit <path>` hands the hook an index of its own: rust-gate reads it at the top, never .git/index, which holds a
    // rust/refuse this commit leaves out (/code-review: the step's index was dropped for any folder but the top)
    std::fs::remove_file(s.path(cdn)).expect("rm");
    s.stage("rust/refuse", "one\n");
    std::fs::remove_file(s.path("rust/refuse")).expect("rm");
    s.write("rust/gate/notes.txt", "three\n");
    let (ok, said) = s.hooked(&["commit", "-qm", "only", "--", "rust/gate/notes.txt"]);
    assert!(ok, "git commit <path> judged on the real index:\n{said}");
}

