/// pre-push's guards before any test: a merge in progress, a worktree pushing main, a branch another session holds, a tip
/// whose last mix precommit failed. Each refusal names its reason.
#[test]
fn hook_pre_push_guards_refuse_with_their_reason() {
    let _budget = TestBudget::new();
    let Some(top) = monorepo() else { return };
    let s = Scratch::new("push-guards", &top).worktree();
    s.remote();
    s.stage("notes.txt", "two\n");
    s.fixture("a change");
    let (ok, said) = s.push("refs/heads/main");
    assert!(
        !ok && said
            .contains("pre-push: a worktree pushes its own branch and opens a PR, never main"),
        "{said}"
    );
    let head = String::from_utf8(
        s.command("git")
            .args(["rev-parse", "HEAD"])
            .output()
            .expect("git")
            .stdout,
    )
    .expect("utf8");
    let merge_head = s.dir.0.join("main/.git/worktrees/task/MERGE_HEAD");
    std::fs::write(&merge_head, &head).expect("MERGE_HEAD");
    let (ok, said) = s.push("refs/heads/task/x");
    assert!(
        !ok && said.contains("pre-push: a merge is still in progress"),
        "{said}"
    );
    std::fs::remove_file(&merge_head).expect("rm");
    // a GitHub remote by its fetch URL, pushed to the bare one
    s.git(&["remote", "set-url", "origin", "git@github.com:o/r.git"]);
    s.git(&[
        "remote",
        "set-url",
        "--push",
        "origin",
        &s.dir.0.join("origin.git").to_string_lossy(),
    ]);
    let app = s.dir.0.join("app");
    std::fs::write(&app, "#!/bin/sh\n[ \"$1\" = review ] && echo 'review push: refused: o/r:task/x is held by review-x' && exit 1\nexit 0\n").expect("app");
    std::fs::set_permissions(&app, std::os::unix::fs::PermissionsExt::from_mode(0o755))
        .expect("chmod");
    let (ok, said) = s.push("refs/heads/task/x");
    assert!(
        !ok && said.contains("pre-push: review push: refused: o/r:task/x is held by review-x"),
        "{said}"
    );
    std::fs::remove_file(&app).expect("rm");
    let tree = String::from_utf8(
        s.command("git")
            .args(["rev-parse", "HEAD^{tree}"])
            .output()
            .expect("git")
            .stdout,
    )
    .expect("utf8");
    std::fs::write(
        s.dir.0.join("main/.git/precommit-results"),
        format!("{} 1 credo: a warning\n", tree.trim()),
    )
    .expect("results");
    let (ok, said) = s.push("refs/heads/task/x");
    assert!(
        !ok && said.contains("its last mix precommit failed (exit 1): credo: a warning"),
        "{said}"
    );
}

