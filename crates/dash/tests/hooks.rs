//! .githooks/pre-commit and pre-push run by git itself on a scratch repository, the one-line hook calling this build's dash
//! (task rust-git-hooks-port; before it rust-hook-tests; @nha, 2026-11-10: « these seem easier as code gates than prompts »):
//! the shell rust-gate passed the orchestrator's hand check and refused every task's rust/ commit, since the check ran without
//! a hook's GIT_DIR. Each step's refusal says why, a test per step (dash_gate::hook).
//!
//! The scratch repository holds the real hooks and bin/bounded; the tools a step calls are stubs that fail silently when
//! `<stub>.fail` is staged, so a refusal's reason must come from the hook. rust/ holds a tiny workspace: its dash-gate refuses
//! a staged rust/refuse, or one on disk. Beside rust/ only in the monorepo: the mirror holds rust/ alone. The pre-commit runs
//! these when a hook or dash_gate::hook changes (its hooks-tests step).
use dash_meter::TestDir;
use dash_meter::memory::TestBudget;
use dash_meter::monorepo;
use std::path::{Path, PathBuf};
use std::process::Command;

/// HTML written with ‹ › for < >: the workspace rule the_dash_crate_holds_no_html keeps tag literals in dash_surface alone
/// (leaked: a test's few fixtures, so each reads as a literal)
fn h(s: &str) -> &'static str {
    Box::leak(s.replace('‹', "<").replace('›', ">").into_boxed_str())
}

