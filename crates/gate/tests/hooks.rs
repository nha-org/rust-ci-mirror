//! .githooks/pre-commit run by git itself, on a scratch repository (task rust-hook-tests; @nha, 2026-11-10: « these seem
//! easier as code gates than prompts »): rust-gate passed the orchestrator's hand check and refused every task's rust/
//! commit, since the check ran without a hook's GIT_DIR. Each step's refusal says why, a test per step.
//!
//! The scratch repository holds the real hook, timed.sh, bin/ci/no-elixir.sh and bin/bounded; the tools a step calls are
//! stubs that fail silently when `<stub>.fail` exists, so a refusal's reason must come from the hook. rust/ holds a tiny
//! workspace: its dash-gate refuses a staged rust/refuse, its dash fails on ../dash.fail. Beside rust/ only in the
//! monorepo: the mirror holds rust/ alone. CI runs it in explainer-gate.yml.
use dash_meter::TestDir;
use dash_meter::memory::TestBudget;
use std::path::{Path, PathBuf};
use std::process::Command;

use dash_meter::monorepo;

const PY_STUB: &str = "import os, sys\nsys.exit(os.path.exists(__file__ + '.fail'))\n";
// `bin/toolchain mix <task>`: fails when `toolchain.fail-<task>` exists
const TOOLCHAIN_STUB: &str = "#!/bin/sh\n[ -e \"$0.fail-$2\" ] && exit 1\nexit 0\n";
// its attribute split: every_test_has_a_budget counts each literal one as a test of this file
const GATE_STUB: &str = concat!(
    "#[",
    r#"test]
fn staged() {
    let git = |args: &[&str]| {
        let out = std::process::Command::new("git").args(args).output().expect("git");
        String::from_utf8_lossy(&out.stdout).trim().to_string()
    };
    // under the hook's GIT_DIR, git takes the current folder for the top, as the real gate's git did
    let top = git(&["rev-parse", "--show-toplevel"]);
    assert!(std::path::Path::new(&top).join("rust/Cargo.toml").is_file(), "Found: git took {top:?} for the top");
    let files = git(&["ls-files", "--full-name", ":/"]);
    assert!(files.lines().any(|l| l == "rust/Cargo.toml"), "Found: no index read: {files:?}");
    assert!(!files.lines().any(|l| l == "rust/refuse"), "Found: rust/refuse is staged");
}
"#
);
const DASH_STUB: &str = "fn main() {\n    std::process::exit(std::path::Path::new(\"../dash.fail\").exists() as i32)\n}\n";
const LOCK: &str = "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"dash\"\nversion = \"0.1.0\"\n\n[[package]]\nname = \"dash-gate\"\nversion = \"0.1.0\"\n";

struct Scratch {
    dir: TestDir,
    /// The checkout commits run in: the main one, or a linked worktree as a task session's
    root: PathBuf,
}

impl Scratch {
    /// The fixture, committed with no hook; every later commit runs the real one.
    fn new(name: &str, top: &Path) -> Self {
        let dir = TestDir::new(&format!("hooks-{name}"));
        let root = dir.0.join("main");
        let s = Self { dir, root };
        for path in [
            ".githooks/pre-commit",
            ".githooks/timed.sh",
            "bin/ci/no-elixir.sh",
            "bin/bounded",
        ] {
            let to = s.path(path);
            std::fs::create_dir_all(to.parent().expect("a folder")).expect("mkdir");
            std::fs::copy(top.join(path), &to).expect(path); // its mode too
        }
        s.write("forge.env", "DEFAULT_BRANCH=main\n");
        for stub in [
            ".claude/skills/custom-cv/europass.py",
            "private/dashboard/priv/commands/comments-anchored",
            "private/dashboard/test/scripts/offline-check",
        ] {
            s.write(stub, PY_STUB);
        }
        s.write("private/dashboard/bin/toolchain", TOOLCHAIN_STUB);
        s.chmod_x("private/dashboard/bin/toolchain");
        s.write("private/dashboard/bin/helper", "one\n");
        s.write("private/dashboard/priv/commands/helper", "one\n");
        s.write("private/dashboard/lib/a.ex", "one\ntwo\n");
        s.write("private/docs/notes.exs", "one\n");
        s.write("src/a.clj", "one\n");
        s.write("notes.txt", "one\n");
        s.write(
            "rust/Cargo.toml",
            "[workspace]\nmembers = [\"gate\", \"dash\"]\nresolver = \"3\"\n",
        );
        s.write("rust/Cargo.lock", LOCK);
        for (krate, file, body) in [
            ("gate", "src/lib.rs", GATE_STUB),
            ("dash", "src/main.rs", DASH_STUB),
        ] {
            let name = if krate == "gate" { "dash-gate" } else { "dash" };
            s.write(
                &format!("rust/{krate}/Cargo.toml"),
                &format!("[package]\nname = \"{name}\"\nversion = \"0.1.0\"\nedition = \"2024\"\n"),
            );
            s.write(&format!("rust/{krate}/{file}"), body);
        }
        s.write("rust/gate/notes.txt", "one\n");
        // an empty test binary of that name, as the real crate has: the pre-commit's `not binary(hooks)` must match one
        s.write("rust/gate/tests/hooks.rs", "");
        s.git(&["init", "-q", "-b", "main"]);
        s.git(&["add", "."]);
        s.git(&["-c", "core.hooksPath=/dev/null", "commit", "-qm", "fixture"]);
        s.git(&["update-ref", "refs/remotes/origin/main", "HEAD"]);
        s
    }

    /// Commits from here on run in a linked worktree, where git gives the hook GIT_DIR (a main checkout's hook gets
    /// none): the rust-gate refusal of every task's rust/ commit showed there alone.
    fn worktree(mut self) -> Self {
        self.git(&["worktree", "add", "-q", "../task"]);
        self.root = self.dir.0.join("task");
        self
    }

    fn path(&self, rel: &str) -> PathBuf {
        self.root.join(rel)
    }

    fn write(&self, rel: &str, text: &str) {
        let file = self.path(rel);
        std::fs::create_dir_all(file.parent().expect("a folder")).expect("mkdir");
        std::fs::write(file, text).expect("write");
    }

    fn chmod_x(&self, rel: &str) {
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(self.path(rel), std::fs::Permissions::from_mode(0o755))
            .expect("chmod");
    }

    /// Git here alone: the hook a test runs under (the pre-commit's rust-gate) sets GIT_DIR and GIT_INDEX_FILE, which
    /// would aim every git below at the real repository, and his global config (signing, fsmonitor) stays out.
    fn command(&self, program: &str) -> Command {
        let mut command = Command::new(program);
        for (key, _) in std::env::vars_os().filter(|(k, _)| {
            let k = k.to_string_lossy();
            k.starts_with("GIT_") || k.starts_with("NEXTEST")
        }) {
            command.env_remove(key);
        }
        command
            .env("GIT_CONFIG_GLOBAL", "/dev/null")
            .env("GIT_CONFIG_NOSYSTEM", "1")
            // the stub workspace builds in the scratch, never in a checkout's target (rust/CLAUDE.md rule 2)
            .env("CARGO_TARGET_DIR", self.path("target"))
            .current_dir(&self.root);
        command
    }

    fn git(&self, args: &[&str]) {
        let out = self
            .command("git")
            .args(["-c", "user.name=t", "-c", "user.email=t@t"])
            .args(args)
            .output()
            .expect("git");
        assert!(
            out.status.success(),
            "git {args:?}: {}",
            String::from_utf8_lossy(&out.stderr)
        );
    }

    /// `git commit` through .githooks: its exit and all the hook printed.
    fn commit(&self) -> (bool, String) {
        let out = self
            .command("git")
            .args(["-c", "user.name=t", "-c", "user.email=t@t"])
            .args(["-c", "core.hooksPath=.githooks", "commit", "-qm", "case"])
            .output()
            .expect("git commit");
        let said = String::from_utf8_lossy(&out.stdout).to_string()
            + &String::from_utf8_lossy(&out.stderr);
        (out.status.success(), said)
    }

    fn stage(&self, rel: &str, text: &str) {
        self.write(rel, text);
        self.git(&["add", rel]);
    }

    fn passes(&self, case: &str) {
        let (ok, said) = self.commit();
        assert!(ok, "{case}: refused\n{said}");
    }

    /// Refused, and what it printed holds `reason`; the index is put back for the next case.
    fn refuses(&self, case: &str, reason: &str) {
        let (ok, said) = self.commit();
        assert!(!ok, "{case}: committed\n{said}");
        assert!(said.contains(reason), "{case}: no « {reason} » in\n{said}");
        self.git(&["reset", "-q", "--hard"]);
    }
}

/// The six cases of elixir-shrinks, now no-elixir: grown, shrunk, a docs .exs changed and a new .exs are refused; a
/// deleted .ex and a Rust-only change pass.
#[test]
fn hook_no_elixir_refuses_four_cases_and_passes_two() {
    let _budget = TestBudget::new();
    let Some(top) = monorepo() else { return };
    let s = Scratch::new("no-elixir", &top).worktree();
    let why = "Elixir is being retired";
    s.stage("private/dashboard/lib/a.ex", "one\ntwo\nthree\n");
    s.refuses("grown", why);
    s.stage("private/dashboard/lib/a.ex", "one\n");
    s.refuses("shrunk", why);
    s.stage("private/docs/notes.exs", "two\n");
    s.refuses("a docs .exs changed", why);
    s.stage("private/new.exs", "one\n");
    s.refuses("a new .exs", "private/new.exs");
    s.git(&["rm", "-q", "private/dashboard/lib/a.ex"]);
    s.passes("a deleted .ex");
    s.stage("rust/gate/notes.txt", "two\n");
    s.passes("a Rust-only change");
}

/// rust-gate runs the scratch dash-gate on the index being committed: a clean tree passes (the run under the hook's
/// GIT_DIR refused every one), a staged rust/refuse is refused with the gate's own line.
#[test]
fn hook_rust_gate_passes_a_clean_tree_and_refuses_with_its_reason() {
    let _budget = TestBudget::new();
    let Some(top) = monorepo() else { return };
    let s = Scratch::new("rust-gate", &top).worktree();
    s.stage("rust/gate/notes.txt", "two\n");
    s.passes("a clean rust/ change");
    s.stage("rust/refuse", "one\n");
    let (ok, said) = s.commit();
    assert!(!ok, "rust/refuse committed\n{said}");
    assert!(
        said.contains("Found: rust/refuse is staged")
            && said.contains("pre-commit: dash-gate fails on this tree"),
        "{said}"
    );
}

/// hooks-tests runs the hooks tests when a commit touches what they test (task rust-ci-off-mac: no CI machine can): a
/// failing one refuses with its step's line, a commit elsewhere never runs them.
#[test]
fn hook_hooks_tests_run_when_the_hook_or_its_tests_change() {
    let _budget = TestBudget::new();
    let Some(top) = monorepo() else { return };
    let s = Scratch::new("hooks-tests", &top).worktree();
    s.stage("notes.txt", "elsewhere\n");
    s.passes("a commit that touches neither");
    s.stage(
        "rust/gate/tests/hooks.rs",
        concat!(
            "#[",
            "test]\nfn fails() {\n    panic!(\"a hook test fails\");\n}\n"
        ),
    );
    let (ok, said) = s.commit();
    assert!(!ok, "a failing hooks test committed\n{said}");
    assert!(
        said.contains("pre-commit: the hooks tests fail on this tree"),
        "{said}"
    );
}

