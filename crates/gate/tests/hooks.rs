/// A step whose tool passes, then fails with no word: the hook names the step. The three Python checks and the lint.
fn silent_step(step: &str, fail: &str) {
    let Some(top) = monorepo() else { return };
    let s = Scratch::new(step, &top);
    s.stage("notes.txt", "two\n");
    s.passes(&format!("{step} passes"));
    s.write(fail, "");
    s.stage("notes.txt", "three\n");
    s.refuses(step, &format!("pre-commit: {step} refused this commit"));
}

